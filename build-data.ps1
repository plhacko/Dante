# Builds data.js from data/cards/*.json and data/games/*.json, so the app and the
# organizer monitor load all game data with a plain <script> tag (works on GitHub Pages
# and when a page is opened straight from disk, where fetch() of local files is blocked).
# Run via build-data.bat after adding or editing any JSON in data/.
# Translations sit next to the Czech card as data/cards/<id>.en.json and <id>.de.json; they must keep
# the Czech card's points, answers and item counts (tests/run_tests.py checks it).
# It also stamps a version (hash of data.js, style.css and js/*.js) on the local files that index.html
# and the monitor load, so a plain refresh fetches them anew after a deploy - run it after changing JS or CSS too.
$ErrorActionPreference = 'Stop'
# file order must not depend on the Windows locale (Czech sorts "ch" after "h")
[System.Threading.Thread]::CurrentThread.CurrentCulture = [Globalization.CultureInfo]::InvariantCulture

$dir  = $PSScriptRoot
$out  = Join-Path $dir 'data.js'
$utf8 = New-Object System.Text.UTF8Encoding $false
$errors = 0

function Read-Folder($sub) {
  $items = @()
  foreach ($file in Get-ChildItem -Path (Join-Path $dir "data\$sub") -Filter '*.json' | Sort-Object Name) {
    $text = [System.IO.File]::ReadAllText($file.FullName, $utf8).Trim()
    try {
      $null = $text | ConvertFrom-Json
    } catch {
      Write-Host "  CHYBA  $sub\$($file.Name)  (neplatny JSON: $($_.Exception.Message))" -ForegroundColor Red
      $script:errors++
      continue
    }
    $items += "    `"$($file.BaseName)`": $text"
    Write-Host "  OK     $sub\$($file.Name)"
  }
  return $items
}

$cards = Read-Folder 'cards'
$games = Read-Folder 'games'

$js = "// Generated by build-data.bat from data/cards/*.json and data/games/*.json - do not edit by hand.`n" +
      "window.DANTE_DATA = {`n  cards: {`n" + ($cards -join ",`n") + "`n  },`n  games: {`n" + ($games -join ",`n") + "`n  }`n};`n"
[System.IO.File]::WriteAllText($out, $js, $utf8)

# ---- version stamp ----
$parts = @('data.js', 'style.css') + (Get-ChildItem -Path (Join-Path $dir 'js') -Filter '*.js' | Sort-Object Name | ForEach-Object { 'js/' + $_.Name })
$all = ($parts | ForEach-Object { [System.IO.File]::ReadAllText((Join-Path $dir $_), $utf8).Replace("`r`n", "`n") }) -join "`n"
$sha = [System.Security.Cryptography.SHA256]::Create()
$ver = (($sha.ComputeHash($utf8.GetBytes($all)) | Select-Object -First 4 | ForEach-Object { $_.ToString('x2') }) -join '')
function Stamp($file, $pattern) {
  $path = Join-Path $dir $file
  $html = [System.IO.File]::ReadAllText($path, $utf8)
  $html = [regex]::Replace($html, '((?:src|href)="' + $pattern + ')(\?v=[0-9a-f]*)?"', '$1?v=' + $ver + '"')
  [System.IO.File]::WriteAllText($path, $html, $utf8)
}
Stamp 'index.html' '(?:data\.js|style\.css|js/[a-z0-9-]+\.js)'
Stamp '_poradatel\monitor.html' '(?:\.\./data\.js|monitor\.js|monitor\.css)'

Write-Host ""
Write-Host "Karet: $($cards.Count), her: $($games.Count)  ->  data.js, verze $ver"
if ($errors -gt 0) { Write-Host "Chyb: $errors" -ForegroundColor Red; exit 1 }
